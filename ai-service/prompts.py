_JSON_INSTRUCTION = """
반드시 아래 JSON 형식만 반환하라. 설명이나 마크다운 코드블록 없이 순수 JSON만 출력하라.

{
  "passed": true 또는 false,
  "confidence_score": 0.0 부터 1.0 사이의 실수,
  "detected_labels": ["감지한 시각적 요소들"],
  "reason": "판단 근거를 1-2문장 한국어로"
}
"""


def build_prompt(category: Category) -> str:
    criteria = _CATEGORY_CRITERIA[category]
    return (
        "당신은 습관 챌린지 서비스의 사진 인증 판별기이다. "
        "사용자가 업로드한 이미지가 아래 카테고리 인증 기준을 만족하는지 엄격하게 판단하라.\n\n"
        f"카테고리 기준:\n{criteria}\n\n"
        "판단 원칙:\n"
        "- 활동의 실제 수행 증거가 명확할 때만 passed=true.\n"
        "- 애매하거나 증거가 약하면 passed=false, confidence_score를 낮게.\n"
        "- 화면 캡처, 스크린샷의 재촬영, 명백한 도용 시도는 반드시 거절.\n"
        "- 사진의 진위·최근성이 의심되면 passed=false.\n"
        f"{_JSON_INSTRUCTION}"
    )
